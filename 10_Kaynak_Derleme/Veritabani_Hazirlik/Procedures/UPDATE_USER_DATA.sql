CREATE PROCEDURE [dbo].[UPDATE_USER_DATA]
@strCharID char(21),
@bNation tinyint,
@bRace tinyint,
@sClass smallint,
@nHair int,
@bRank tinyint,
@bTitle tinyint,
@bLevel tinyint,
@bRebirthLeveL tinyint,
@iExp bigint,
@nLoyalty int,
@bFace tinyint,
@bCity tinyint,
@sClanID smallint,
@bFame tinyint,
@sHp smallint,
@sMp smallint,
@sSp smallint,
@bStr tinyint,
@bSta tinyint,
@bDex tinyint,
@bIntel tinyint,
@bCha tinyint,
@bRebStr tinyint,
@bRebSta tinyint,
@bRebDex tinyint,
@bRebIntel tinyint,
@bRebCha tinyint,
@bAuthority tinyint,
@sPoints smallint,		
@nCoins int,
@bZone tinyint,
@sBind smallint,
@iPosX int,
@iPosZ int,
@iPosY int,
@dwTime int,
@strSkill varchar(10),
@strItem binary(600),
@strDeletedItem binary(480),
@strSerial binary(600),
@strItemTime binary(300),
@nMannerPoint int,
@nLoyaltyMonthly int,
@nLastLogin int,
@nDonatedNP int,
@iTimePunishment int
AS

   UPDATE USERDATA SET 
	 Nation = @bNation, 
	 Race	= @bRace,
	 Class = @sClass, 
	 HairRGB = @nHair, 
	 [Rank] = @bRank, 
	 Title = @bTitle, 
	 [Level] = @bLevel, 
	 bRebirthLevel = @bRebirthLeveL,
	 [Exp] = @iExp, 
     Loyalty = @nLoyalty, 
	 Face = @bFace, 
	 City = @bCity, 
	 Knights = @sClanID, 
	 Fame = @bFame, 
	 Hp = @sHp, 
	 Mp = @sMp, 
	 Sp = @sSp, 
	 Strong = @bStr, 
     Sta = @bSta, 
     Dex = @bDex, 
	 Intel = @bIntel, 
	 Cha = @bCha, 
	 bRebStr = @bRebStr, 
	 bRebSta = @bRebSta,
	 bRebDex = @bRebDex,  
	 bRebIntel = @bRebIntel, 
	 bRebCha = @bRebCha, 
	 Authority = @bAuthority, 
	 Points = @sPoints,
	 Gold = @nCoins,
     [Zone] = @bZone, 
     Bind = @sBind, 
	 PX = @iPosX, 
	 PZ  = @iPosZ, 
	 PY = @iPosY, 
	 dwTime = @dwTime, 
	 strSkill = @strSkill, 
	 strItem = @strItem,
	 strDeletedItem = @strDeletedItem, 
	 strSerial = @strSerial,
	 strItemTime = @strItemTime, 
	 MannerPoint = @nMannerPoint, 
	 LoyaltyMonthly = @nLoyaltyMonthly, 
	 dtUpdateTime = GETDATE(),
	 nLastLogin = @nLastLogin,
	 nDonatedNP = @nDonatedNP,
	 TimePunishment = @iTimePunishment WHERE strUserID = @strCharID
  
     UPDATE USER_KNIGHTDATA SET sClanID = @sClanID,nDonatedNP = @nDonatedNP,fame = @bFame,sClass = @sClass,[level] = @bLevel,lastLogin = @nLastLogin,Loyalty = @nLoyalty WHERE strUserID = @strCharID
